  // o contorno em volta do preenchimento (vizinho de lado, de cima ou de baixo)
  function contornar(d) {
    return d.map(function (l, y) {
      return l.split('').map(function (c, x) {
        if (c !== '.') return c;
        var viz = [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]].some(function (p) {
          var r = d[p[1]];
          return r && r[p[0]] && r[p[0]] !== '.' && r[p[0]] !== 'k';
        });
        return viz ? 'k' : '.';
      }).join('');
    });
  }
  // só as cores das letras que o desenho usa (o molde da cabeça tem 8 lugares de cor)
  function paletaDe(linhas, cores) {
    var p = {};
    linhas.join('').split('').forEach(function (c) { if (cores[c]) p[c] = cores[c]; });
    return p;
  }
  function erro(id, m) { throw new Error('_lojaMoldes.peca(' + id + '): ' + m); }

  function peca(id, nome, raridade, bonus, forma, tema) {
    var tipo = id.split('-')[0], cores = Object.assign({}, FIXAS, TEMAS[tema]);
    if (!LOJA[tipo]) erro(id, 'tipo sem loja');
    if (!TEMAS[tema]) erro(id, 'tema desconhecido: ' + tema);
    var precos = R.config.vila.precos;
    R.ItensCatalogo.registrar({ id: id, nome: nome, tipo: tipo, slot: SLOT[tipo], raridade: raridade, bonus: bonus,
      arenas: [], loja: LOJA[tipo], preco: precos[raridade], icone: 'item:' + id });
    var f, desenho;
    if (tipo === 'espada') {
      f = ESPADAS[forma];
      if (!f) erro(id, 'forma de espada desconhecida: ' + forma);
      V[id] = { paleta: paletaDe(f.mao, { w: cores.c, l: cores.a, o: cores.d, g: cores.e, p: cores.b, r: cores.r }), linhas: f.mao.slice() };
    } else if (tipo === 'capacete' || tipo === 'chapeu') {
      f = CABECAS[forma];
      if (!f) erro(id, 'forma de cabeça desconhecida: ' + forma);
      V[id] = { paleta: paletaDe(f.frente.concat(f.lado), cores), esconde: ['B'], vistas: {
        frente: { y: f.y, linhas: f.frente.slice() }, lado: { y: f.y, linhas: f.lado.slice() } } };
    } else {
      f = (tipo === 'armadura' ? ARMADURAS : BOTAS)[forma];
      if (!f) erro(id, 'forma de ' + tipo + ' desconhecida: ' + forma);
      var m = { paleta: { a: cores.a, b: cores.b, c: cores.c, d: cores.d, e: cores.e, w: cores.w } };
      Object.keys(f).forEach(function (k) { if (k !== 'icone') m[k] = f[k]; });
      V[id] = m;
    }
    desenho = contornar(f.icone);
    var ic = {};
    ic['item:' + id] = { n: nome.toLowerCase(), p: Object.assign({ k: '#3a2446' }, paletaDe(desenho, cores)), d: desenho };
    R.registrarIcones(ic);
  }

  R._lojaMoldes = { TEMAS: TEMAS, peca: peca, contornar: contornar,
    FORMAS: { espada: Object.keys(ESPADAS), cabeca: Object.keys(CABECAS), armadura: Object.keys(ARMADURAS), botas: Object.keys(BOTAS) } };
